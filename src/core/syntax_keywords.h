using namespace std::literals;

// バケット最大長。全テーブルで現状最長 23 (`ConstructorParameters`) なので余裕を持たせて 32。
inline constexpr size_t KEYWORD_MAX_LEN = 32;

// type-erased view。LANGUAGE_DEFS で言語ごとに異なる N を 1 つの配列に格納するため、
// 各 BucketedTable<N> から暗黙変換できる軽量ビューを使う。
struct KeywordTable {
    std::span<const mendo::doc_string_view> entries;
    std::span<const uint16_t> bucket_offsets; // size = KEYWORD_MAX_LEN + 2

    [[nodiscard]] constexpr bool empty() const noexcept
    {
        return entries.empty();
    }

    [[nodiscard]] constexpr bool contains(mendo::doc_string_view word) const noexcept
    {
        if (entries.empty()) {
            return false;
        }
        const size_t len = word.size();
        if (len == 0 || len + 1 >= bucket_offsets.size()) {
            return false;
        }
        const size_t start = bucket_offsets[len];
        const size_t end = bucket_offsets[len + 1];
        if (start == end) {
            return false;
        }
        return std::ranges::binary_search(entries.subspan(start, end - start), word);
    }
};

template <size_t N>
struct BucketedTable {
    std::array<mendo::doc_string_view, N> entries{};
    std::array<uint16_t, KEYWORD_MAX_LEN + 2> bucket_offsets{};

    constexpr operator KeywordTable() const noexcept
    {
        return KeywordTable{
            std::span<const mendo::doc_string_view>{ entries },
            std::span<const uint16_t>{ bucket_offsets }
        };
    }
};

template <size_t N>
consteval BucketedTable<N> MakeBucketed(std::array<mendo::doc_string_view, N> arr)
{
    // (length, lex) 辞書順でソート。同じ長さ内では二分探索のために lex 昇順を維持する。
    std::ranges::sort(arr, [](mendo::doc_string_view a, mendo::doc_string_view b) {
        if (a.size() != b.size()) {
            return a.size() < b.size();
        }
        return a < b;
    });

    BucketedTable<N> r;
    r.entries = arr;

    // 各長さの個数をカウント、prefix-sum で開始位置に変換。
    for (const auto& s : arr) {
        if (s.size() <= KEYWORD_MAX_LEN) {
            r.bucket_offsets[s.size() + 1]++;
        }
    }
    for (size_t i = 1; i < r.bucket_offsets.size(); i++) {
        r.bucket_offsets[i] = static_cast<uint16_t>(r.bucket_offsets[i] + r.bucket_offsets[i - 1]);
    }
    return r;
}

