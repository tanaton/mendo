// 各言語のキーワード・型名テーブル。syntax.cpp からのみ include される内部ヘッダ。
// 長さバケット + 各バケット内ソート済み配列。
// 識別子検索時は word.size() で対応バケットへ直接ジャンプし、典型 1〜10 件の小バケットを
// 二分探索する。長さ違いのキーワードと wmemcmp する無駄を排除する。
// MakeBucketed は consteval なのでバケット境界はコンパイル時に確定する。
#pragma once
#include "doc_text.h"
#include <algorithm>
#include <array>
#include <span>
#include <string_view>
#include <tuple>
#include <cstdint>

